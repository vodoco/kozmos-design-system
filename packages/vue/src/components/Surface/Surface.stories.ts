import type { Meta, StoryObj } from "@storybook/vue3";
import { h } from "vue";
import { KozmosSurface, KozmosText } from "../../index";

/**
 * Vue's Surface: the stories React's has, with the same names and args,
 * each inside the KozmosThemeProvider the Storybook's decorator gives every
 * story, on React's frame: a gradient for glass to show through, and a line
 * of Text. The frame is drawn with a render function, not a template, so
 * its text is React's to the node: a template keeps the spaces around a
 * line's words (test/parity/story-renders.parity.spec.ts).
 * test/parity/surface.parity.spec.ts holds Vue's render to React's.
 * Generated by `port Surface`, then drawn by hand.
 */
type Args = Record<string, unknown>;

const meta: Meta<Args> = {
  title: "Vue/Core/Layout/Surface",
  component: KozmosSurface,
  parameters: { layout: "padded" },
  render: (args) => ({
    setup: () => {
      const { className, children, ...props } = args;
      return () =>
        h(
          "div",
          {
            class: "relative min-h-[280px] rounded-panel p-6",
            style:
              "background-image: linear-gradient(135deg, var(--primitives-colors-theme-500) 0%, var(--primitives-colors-theme-200) 45%, var(--primitives-colors-background-300) 100%)",
          },
          [
            h(
              KozmosText,
              { class: "mb-24 text-sm" },
              () =>
                "Solid covers what is behind it; glass lets it show through, blurred and saturated by the token.",
            ),
            h(
              KozmosSurface,
              { ...props, class: className },
              () => children as string,
            ),
          ],
        );
    },
  }),
  args: {
    className: "rounded-container p-4 text-foreground shadow-floating",
    children: "A card over the map.",
  },
};

export default meta;
type Story = StoryObj<Args>;

export const Solid: Story = {};

export const Glass: Story = {
  args: {
    variant: "glass",
    children: "A card over the map, on the glass surface role.",
  },
};

export const GlassPanel: Story = {
  args: {
    variant: "glass",
    className: "rounded-panel p-6 text-foreground shadow-overlay",
    children: "A panel, radius Panel, elevation Overlay.",
  },
};
