import type { Meta, StoryObj } from "@storybook/vue3";
import { h } from "vue";
import { KozmosFieldWrapper, KozmosInput } from "../../index";

/**
 * Vue's FieldWrapper: the stories React's has, with the same names, each
 * drawn as React's story draws it, inside the KozmosThemeProvider the
 * Storybook's decorator gives every story. React's meta gives every story
 * an Input as its `children`, a node Vue's args cannot carry: here each
 * story draws the native KozmosInput in the default slot.
 * test/parity/field-wrapper.parity.spec.ts draws each in both and holds
 * Vue's render to React's. Generated by `port FieldWrapper`.
 */
type Args = Record<string, unknown>;

const meta: Meta<Args> = {
  title: "Vue/Core/Inputs/FieldWrapper",
  component: KozmosFieldWrapper,
  parameters: { layout: "centered" },
  argTypes: {
    status: {
      control: "select",
      options: ["default", "error", "warning", "success"],
    },
  },
};

export default meta;
type Story = StoryObj<Args>;

const placeholder = () => h(KozmosInput, { placeholder: "Placeholder" });

export const Default: Story = {
  args: {
    description: "Use supporting guidance when the field needs it.",
    helperText: "Helper text",
    label: "Label",
    required: true,
    status: "default",
  },
  // `description` is a node in React, Vue's #description slot.
  render: (args) => ({
    setup: () => () => {
      const { description, ...props } = args;
      return h(
        KozmosFieldWrapper,
        { ...props, class: "w-80" },
        {
          ...(description ? { description: () => String(description) } : {}),
          default: placeholder,
        },
      );
    },
  }),
};

export const ValidationStates: Story = {
  render: () => ({
    setup: () => () =>
      h("div", { class: "grid w-80 gap-5" }, [
        h(
          KozmosFieldWrapper,
          { label: "Default", helperText: "Helper text", status: "default" },
          { default: placeholder },
        ),
        h(
          KozmosFieldWrapper,
          { label: "Error", error: "This field is required." },
          { default: placeholder },
        ),
        h(
          KozmosFieldWrapper,
          {
            label: "Warning",
            helperText: "Check this value.",
            status: "warning",
          },
          { default: placeholder },
        ),
        h(
          KozmosFieldWrapper,
          { label: "Success", helperText: "Looks good.", status: "success" },
          { default: placeholder },
        ),
      ]),
  }),
};
