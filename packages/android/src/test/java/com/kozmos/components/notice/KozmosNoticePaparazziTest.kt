/**
 * GAP-160: Notice's four tones with their marks, the progress arc (still,
 * animations off) and the done check at the inline end, a collapsed detail
 * and the action under the text, on the page surface in each theme.
 */
class KozmosNoticePaparazziTest {
    @get:Rule
    val paparazzi = Paparazzi(maxPercentDifference = CROSS_PLATFORM_MAX_PERCENT_DIFFERENCE)

    @Test
    fun theNoticesInLightMode() = snapshotIn(dark = false)

    @Test
    fun theNoticesInDarkMode() = snapshotIn(dark = true)

    private fun snapshotIn(dark: Boolean) {
        paparazzi.snapshot {
            CompositionLocalProvider(
                LocalKozmosUseDarkTokens provides dark,
                LocalKozmosAnimatorScale provides 0f
            ) {
                KozmosMaterialTheme {
                    Column(
                        verticalArrangement = Arrangement.spacedBy(8.dp),
                        modifier = Modifier
                            .background(KozmosThemeTokens.semanticsSurface0)
                            .padding(16.dp)
                            .width(352.dp)
                    ) {
                        KozmosNotice(
                            summary = "AI results may be incomplete. Check allergens with the venue.",
                            detail = "These results are AI-assisted and may be incomplete."
                        )
                        KozmosNotice(summary = "Results are generated by AI.", tone = KozmosNoticeTone.Info)
                        KozmosNotice(
                            summary = "If someone's life is in danger, call 112 now",
                            tone = KozmosNoticeTone.Critical,
                            collapsible = false,
                            detail = "Airport staff can help too.",
                            action = {
                                KozmosButton(onClick = {}, variant = KozmosButtonVariant.Destructive) { Text("Call 112") }
                            }
                        )
                        KozmosNotice(summary = "Saving the geometry", tone = KozmosNoticeTone.Info, status = KozmosNoticeStatus.Progress)
                        KozmosNotice(summary = "Geometry is set", tone = KozmosNoticeTone.Success, status = KozmosNoticeStatus.Done)
                        KozmosNotice(
                            summary = "Set Geometry",
                            action = {
                                KozmosButton(onClick = {}, variant = KozmosButtonVariant.Outline) { Text("Set Building Boundary") }
                            }
                        )
                    }
                }
            }
        }
    }
}
