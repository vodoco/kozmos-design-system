/**
 * Kozmos for Claude Design: the consuming page and one API card per
 * component, generated from the code (Olcay's decision 52).
 *
 * Claude Design builds a Kozmos design-system artifact from this repository,
 * and a design session installs it on a canvas. The gap register found two
 * things it lacked (GAP-089, GAP-090): its README named no bundle global, so
 * the Design editor drew lookalikes from the tokens instead of mounting the
 * components, and each component card stopped a few props into the published
 * API and carried no example to mount from. Hand-written copies would drift
 * the day after they were written, so this writes them from what the
 * repository already knows:
 *
 *   - docs/claude-design/README.md: consuming the system — install, the
 *     stylesheet, ThemeProvider, the React peer, a minimal example, where the
 *     cards and the types are — and the artifact's own notes, marked as such;
 *   - docs/claude-design/components/<Name>.md: every part of a component with
 *     every prop the built declarations give it, the Kozmos types those props
 *     take, whatever else the component's module exports, and one example
 *     taken from its stories that is type-checked against the build.
 *
 * `pnpm skills:build` writes them and `pnpm skills:check` fails when they are
 * stale, alongside the AI-facing inventory and changelog.
 */
