import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { format, resolveConfig } from "prettier";

// One canonical artwork, mechanically packaged for each platform. Never redraw.
const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const svg = readFileSync(resolve(root, "assets/brand/pointr-logo.svg"), "utf8");
const paths = [...svg.matchAll(/<path\s+([^>]+)\/?\s*>/g)].map(([, attrs]) => {
  const attribute = (name) =>
    attrs.match(new RegExp("(?:^|\\s)" + name + '="([^"]*)"'))?.[1];
  const d = attribute("d");
  const fill = attribute("fill");
  if (
    !d ||
    !["white", "#747B8B"].includes(fill) ||
    attribute("fill-rule") !== "evenodd"
  ) {
    throw new Error(
      "Unsupported logo path; review the canonical artwork before regenerating.",
    );
  }
  return `    <path android:fillType="evenOdd" android:fillColor="${fill === "white" ? "#FFFFFF" : fill}" android:pathData="${d}" />`;
});
if (
  paths.length !== 4 ||
  !svg.includes('viewBox="0 0 98 34"') ||
  !svg.includes(
    '<rect width="96.19" height="33.6" fill="white" transform="translate(0.905029)"/>',
  )
)
  throw new Error("Unexpected logo geometry");
// The web data URL: the artwork's own bytes, percent-encoding only what a URL
// or the TypeScript string can't carry raw, so spaces, =, /, : and , stay as
// they are. It decodes to the canonical file exactly and costs the bundle
// 0.2 KB less than encoding every character.
const dataUri =
  "data:image/svg+xml," +
  svg.replace(/[\r\n"%#<>?[\\\]^`{|}]/g, encodeURIComponent);
const outputs = {
  "packages/react/src/components/MapAttribution/pointr-logo.ts":
    '// Generated by scripts/build-pointr-brand.mjs. Do not edit.\nexport const pointrLogo = "' +
    dataUri +
    '";\n',
  "packages/ios/Sources/Resources/PointrBrand.xcassets/Contents.json":
    JSON.stringify({ info: { author: "xcode", version: 1 } }, null, 2) + "\n",
  "packages/ios/Sources/Resources/PointrBrand.xcassets/PointrLogo.imageset/Contents.json":
    JSON.stringify(
      {
        images: [{ filename: "pointr-logo.svg", idiom: "universal" }],
        info: { author: "xcode", version: 1 },
        properties: { "preserves-vector-representation": true },
      },
      null,
      2,
    ) + "\n",
  "packages/ios/Sources/Resources/PointrBrand.xcassets/PointrLogo.imageset/pointr-logo.svg":
    svg,
  "packages/android/src/main/res/drawable/kozmos_pointr_logo.xml":
    '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by scripts/build-pointr-brand.mjs. Do not edit. -->\n<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="98dp" android:height="34dp" android:viewportWidth="98" android:viewportHeight="34">\n  <group>\n    <clip-path android:pathData="M0.905029,0 H97.095029 V33.6 H0.905029 Z" />\n' +
    paths.join("\n") +
    "\n  </group>\n</vector>\n",
};
for (const [name, generated] of Object.entries(outputs)) {
  const path = resolve(root, name);
  // Match the commit hook exactly: generated text must be a fixed point of
  // formatting, otherwise a passing pre-commit check becomes stale on commit.
  const content = /\.(ts|json)$/.test(name)
    ? await format(generated, {
        ...(await resolveConfig(path)),
        filepath: path,
      })
    : generated;
  if (process.argv.includes("--check")) {
    if (readFileSync(path, "utf8") !== content)
      throw new Error(`Stale branding asset: ${name}`);
  } else {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, content);
  }
}
console.log(
  "Pointr branding assets " +
    (process.argv.includes("--check") ? "verified" : "generated"),
);
