#!/usr/bin/env node
/**
 * Draws the parts of the home page's cover that CSS masks used to cut, as
 * images a browser rasterizes once. A mask is applied again whenever what it
 * covers is drawn, and the cover is drawn every frame it moves: drawn in
 * software, as CI draws it, the cover's masks held Firefox to 16 to 19
 * frames a second and WebKit to 8, against 61 and 35 without them.
 *
 *  - src/home/cosmos/orbit-<n>.svg — each orbit's line, 1.5 pixels at any
 *    size, faded out where the cover fades it (src/home/cosmos-orbits.json);
 *  - src/home/cosmos/galaxy.svg — the galaxy's violet rings round its warm
 *    core, its arms brighter and dimmer round it, fading out to its edge;
 *  - src/home/cosmos/ring.svg — the ring round the logo, 3 pixels at any
 *    size, its colours turning round it;
 *  - src/home/cosmos/spark.svg — the logo's star in the cover's violet;
 *  - src/home/cosmos/planet-air-violet.svg and planet-air-blue.svg — the
 *    thin glow of air on a planet's lit side.
 *
 * The masks become the images' own: grey wedges, a degree each, for a
 * gradient that turns round a centre, which SVG has no gradient for. Every
 * colour is read from the tokens' dark stylesheet, as the brand script reads
 * them: the cover is drawn in the dark theme whatever the site's.
 *
 *   node scripts/generate-cosmos.mjs            # write every file
 *   node scripts/generate-cosmos.mjs --check    # fail if a file would change
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { tokenValue } from "./generate-brand.mjs";

const SITE_ROOT = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "..",
);
const ART = path.join(SITE_ROOT, "src/home/cosmos");
const ORBITS = path.join(SITE_ROOT, "src/home/cosmos-orbits.json");
const STAR = path.join(SITE_ROOT, "src/brand/kozmos-star.svg");
const DARK_TOKENS = fileURLToPath(
  import.meta.resolve("@kozmos-ds/tokens/css/dark.css"),
);

/** An orbit's line takes its tone's colour. */
export const TONES = {
  violet: "--primitives-colors-theme-variant-2-600",
  lilac: "--primitives-colors-theme-variant-1-700",
  amber: "--primitives-colors-emotional-alert-500",
  faint: "--primitives-colors-transparent-inverted-25",
};

// XML forbids a double hyphen inside a comment, so this names the script.
const HEADER =
  "<!-- Generated by scripts/generate-cosmos.mjs (the site's cover script) from the tokens' dark stylesheet and src/home/cosmos-orbits.json. Change those and run the script; do not edit this file. -->";

const round = (value) => Number(value.toFixed(3));

/**
 * The point at `degrees` round a centre, clockwise from the top, to a
 * hundredth of a unit: a tenth of a pixel on the largest orbit.
 */
function at(cx, cy, r, degrees) {
  const radians = (degrees * Math.PI) / 180;
  const near = (value) => Number(value.toFixed(2));
  return [near(cx + r * Math.sin(radians)), near(cy - r * Math.cos(radians))];
}

/**
 * A stepwise share of a turn's gradient: `stops` are [percent, value] pairs
 * from 0 to 100, read as CSS reads a conic gradient's, linearly between.
 */
export function along(stops, percent) {
  for (let index = 1; index < stops.length; index += 1) {
    const [p1, v1] = stops[index - 1];
    const [p2, v2] = stops[index];
    if (percent <= p2)
      return p1 === p2 ? v2 : v1 + ((v2 - v1) * (percent - p1)) / (p2 - p1);
  }
  return stops[stops.length - 1][1];
}

/**
 * Wedges round (cx, cy), one a degree, from `from` degrees clockwise from
 * the top, each filled with what `fill(percent)` gives at its middle. Each
 * overlaps the next by a little and is opaque, so no seam shows between
 * them; neighbours that are the same are drawn as one.
 */
export function wedges({ cx, cy, r, from, fill }) {
  const runs = [];
  for (let degree = 0; degree < 360; degree += 1) {
    const value = fill(((degree + 0.5) / 360) * 100);
    const last = runs[runs.length - 1];
    if (last && last.value === value) last.end = degree + 1;
    else runs.push({ start: degree, end: degree + 1, value });
  }
  return runs.map(({ start, end, value }) => {
    const a = from + start - 0.25;
    const b = from + end + 0.25;
    const [x1, y1] = at(cx, cy, r, a);
    const [x2, y2] = at(cx, cy, r, b);
    const large = b - a > 180 ? 1 : 0;
    return `<path d="M${cx} ${cy}L${x1} ${y1}A${r} ${r} 0 ${large} 1 ${x2} ${y2}Z" fill="${value}"/>`;
  });
}

/** A mask's grey for an alpha from 0 to 1. */
const grey = (alpha) => {
  const level = Math.round(Math.max(0, Math.min(1, alpha)) * 255);
  return `#${level.toString(16).padStart(2, "0").repeat(3)}`;
};

/** An sRGB colour, #rrggbb or rgb()/rgba(), as [r, g, b, a]. */
export function parseColour(value) {
  const hex = value.match(/^#([0-9a-f]{6})$/i);
  if (hex)
    return [0, 2, 4].map((i) => parseInt(hex[1].slice(i, i + 2), 16)).concat(1);
  const fn = value.match(/^rgba?\(([^)]+)\)$/);
  if (fn) {
    const parts = fn[1]
      .split(/[\s,/]+/)
      .filter(Boolean)
      .map(Number);
    return [parts[0], parts[1], parts[2], parts[3] ?? 1];
  }
  throw new Error(`${value} is not a colour the cover script reads.`);
}

const hexOf = ([r, g, b]) =>
  `#${[r, g, b].map((c) => Math.round(c).toString(16).padStart(2, "0")).join("")}`;

/** The colour a stop list gives at `percent`, mixed in sRGB as CSS mixes. */
function colourAlong(stops, percent) {
  for (let index = 1; index < stops.length; index += 1) {
    const [p1, c1] = stops[index - 1];
    const [p2, c2] = stops[index];
    if (percent <= p2) {
      const t = p1 === p2 ? 1 : (percent - p1) / (p2 - p1);
      return hexOf(c1.map((c, i) => c + (c2[i] - c) * t));
    }
  }
  return hexOf(stops[stops.length - 1][1]);
}

/** A stroke's colour attribute and its opacity, from a token's value. */
function strokeOf(value) {
  const [r, g, b, a] = parseColour(value);
  const colour = hexOf([r, g, b]);
  return a === 1
    ? `stroke="${colour}"`
    : `stroke="${colour}" stroke-opacity="${round(a)}"`;
}

function svg(viewBox, body) {
  return [
    `<svg viewBox="${viewBox}" fill="none" xmlns="http://www.w3.org/2000/svg">`,
    HEADER,
    ...body,
    "</svg>",
    "",
  ].join("\n");
}

/**
 * An orbit's line: the circle the cover's line mask drew, 1.5 pixels wide at
 * any size, faded out over `fade` percent of the turn either side of `from`
 * degrees, as its conic mask faded it.
 */
export function orbitSvg({ from, fade }, colour) {
  const stops = [
    [0, 0],
    [fade, 1],
    [100 - fade, 1],
    [100, 0],
  ];
  return svg("0 0 100 100", [
    '<mask id="fade" maskUnits="userSpaceOnUse" x="0" y="0" width="100" height="100">',
    ...wedges({
      cx: 50,
      cy: 50,
      r: 72,
      from,
      fill: (percent) => grey(along(stops, percent)),
    }),
    "</mask>",
    `<circle cx="50" cy="50" r="49" ${strokeOf(colour)} stroke-width="1.5" vector-effect="non-scaling-stroke" mask="url(#fade)"/>`,
  ]);
}

/** A radial gradient's stops, as `[offset, colour]` with each colour's alpha. */
function stopsOf(stops) {
  return stops.map(([offset, value, alpha = 1]) => {
    const [r, g, b, a] = parseColour(value);
    return `<stop offset="${round(offset)}" stop-color="${hexOf([r, g, b])}" stop-opacity="${round(a * alpha)}"/>`;
  });
}

/** How far the galaxy has faded at `offset` of its radius, as its mask faded it. */
export function falloff(offset) {
  return along(
    [
      [0, 1],
      [0.1, 1],
      [0.4, 0.5],
      [1, 0],
    ],
    offset,
  );
}

/**
 * A radial gradient's stops, each faded as the galaxy fades it: `stops` are
 * `[offset, colour, alpha]`, and a stop is added every `step` between them
 * and at each turn of the fall-off, since a fade times a fade is no longer
 * a straight line. "Transparent" is the stop's own colour at no alpha, as
 * CSS mixes it.
 */
function fadedStops(stops, step = 0.02) {
  const colours = stops.map(([offset, value]) => [
    offset,
    parseColour(value).slice(0, 3),
  ]);
  const alphas = stops.map(([offset, value, alpha = 1]) => [
    offset,
    parseColour(value)[3] * alpha,
  ]);
  const first = stops[0][0];
  const last = stops[stops.length - 1][0];
  const offsets = new Set(stops.map(([offset]) => offset));
  for (let index = 1; first + index * step < last; index += 1)
    offsets.add(round(first + index * step));
  for (const turn of [0.1, 0.4])
    if (turn > first && turn < last) offsets.add(turn);
  return [...offsets]
    .sort((a, b) => a - b)
    .map(
      (offset) =>
        `<stop offset="${round(offset)}" stop-color="${colourAlong(colours, offset)}" stop-opacity="${round(along(alphas, offset) * falloff(offset))}"/>`,
    );
}

/**
 * The galaxy, as its four layered gradients drew it through its two masks:
 * an alpha falling from the centre out, and the arms' brightness round it.
 * The fall-off is drawn into the gradients' own stops, and each repeating
 * gradient's rings are written out one by one: WebKit draws no
 * `spreadMethod="repeat"`, and leaves the rings out. The four layers sit
 * in a group of their own, at an opacity a hair under 1: WebKit masks each
 * child of a masked group on its own, which showed the rings through the
 * core, unless the children are one layer first, and an opacity makes them
 * one. (A pattern would make them one too, but engines draw a pattern's
 * tile coarser than the image, and the rings blur.)
 */
export function galaxySvg(token) {
  const rings = (id, period, value, [clearTo, peak, clearFrom]) => {
    const [r, g, b, a] = parseColour(value);
    const colour = hexOf([r, g, b]);
    const stops = [];
    for (let ring = 0; ring * period + clearFrom <= 100; ring += 1)
      for (const [at, lit] of [
        [clearTo, 0],
        [peak, 1],
        [clearFrom, 0],
      ]) {
        const offset = (ring * period + at) / 100;
        stops.push(
          `<stop offset="${round(offset)}" stop-color="${colour}" stop-opacity="${round(a * lit * falloff(offset))}"/>`,
        );
      }
    return [
      `<radialGradient id="${id}" gradientUnits="userSpaceOnUse" cx="100" cy="100" r="100">`,
      ...stops,
      "</radialGradient>",
    ];
  };
  const conic = [
    [0, 1],
    [12, 0.25],
    [30, 1],
    [45, 0.25],
    [62, 1],
    [80, 0.5],
    [100, 1],
  ];
  return svg("0 0 200 200", [
    "<defs>",
    '<radialGradient id="core" gradientUnits="userSpaceOnUse" cx="100" cy="100" r="100">',
    ...fadedStops([
      [0, token("--primitives-colors-foreground-0")],
      [0.03, token("--primitives-colors-emotional-alert-700")],
      [0.08, token("--primitives-colors-emotional-danger-600")],
      [0.22, token("--primitives-colors-emotional-danger-600"), 0],
    ]),
    "</radialGradient>",
    ...rings(
      "wide",
      7,
      token("--primitives-colors-theme-variant-2-700"),
      [3, 3.6, 4.6],
    ),
    ...rings(
      "fine",
      4.4,
      token("--primitives-colors-theme-variant-2-500"),
      [1.2, 1.6, 2.2],
    ),
    '<radialGradient id="haze" gradientUnits="userSpaceOnUse" cx="100" cy="100" r="100">',
    ...fadedStops([
      [0, token("--primitives-colors-theme-variant-2-400")],
      [0.75, token("--primitives-colors-theme-variant-2-400"), 0],
    ]),
    "</radialGradient>",
    '<mask id="arms" maskUnits="userSpaceOnUse" x="0" y="0" width="200" height="200">',
    ...wedges({
      cx: 100,
      cy: 100,
      r: 145,
      from: 0,
      fill: (percent) => grey(along(conic, percent)),
    }),
    "</mask>",
    "</defs>",
    '<g mask="url(#arms)">',
    '<g opacity="0.999">',
    '<rect width="200" height="200" fill="url(#haze)"/>',
    '<rect width="200" height="200" fill="url(#fine)"/>',
    '<rect width="200" height="200" fill="url(#wide)"/>',
    '<rect width="200" height="200" fill="url(#core)"/>',
    "</g>",
    "</g>",
  ]);
}

/** The ring's colours round it, from -8 degrees, as its conic gradient. */
function ringStops(token) {
  return [
    [0, "--primitives-colors-theme-variant-2-900"],
    [6, "--primitives-colors-theme-variant-2-700"],
    [14, "--primitives-colors-emotional-danger-600"],
    [22, "--primitives-colors-emotional-alert-500"],
    [30, "--primitives-colors-emotional-danger-500"],
    [40, "--primitives-colors-theme-variant-2-400"],
    [50, "--primitives-colors-theme-variant-2-200"],
    [62, "--primitives-colors-theme-variant-2-300"],
    [76, "--primitives-colors-theme-variant-2-500"],
    [88, "--primitives-colors-theme-variant-1-600"],
    [100, "--primitives-colors-theme-variant-2-900"],
  ].map(([percent, name]) => [percent, parseColour(token(name)).slice(0, 3)]);
}

/**
 * The ring: a circle's line 3 pixels wide at any size, painted with its
 * colours in wedges round the centre. The wedges are the line's paint, a
 * pattern, not what a mask cuts: WebKit masks each of a masked group's
 * children on its own, so the wedges' overlaps showed as beads along the
 * line. A pattern's tile is drawn coarser than the image, which colours
 * that turn this slowly do not show.
 */
export function ringSvg(token) {
  const stops = ringStops(token);
  return svg("0 0 100 100", [
    "<defs>",
    '<pattern id="colours" patternUnits="userSpaceOnUse" x="0" y="0" width="100" height="100">',
    ...wedges({
      cx: 50,
      cy: 50,
      r: 72,
      from: -8,
      fill: (percent) => colourAlong(stops, percent),
    }),
    "</pattern>",
    "</defs>",
    '<circle cx="50" cy="50" r="49" stroke="url(#colours)" stroke-width="3" vector-effect="non-scaling-stroke"/>',
  ]);
}

/** The logo's star (src/brand/kozmos-star.svg), in the cover's violet. */
export function sparkSvg(star, token) {
  const colour = hexOf(
    parseColour(token("--primitives-colors-theme-variant-2-900")),
  );
  const viewBox = star.match(/viewBox="([^"]+)"/)?.[1];
  const d = star.match(/<path d="([^"]+)"/)?.[1];
  if (!viewBox || !d) throw new Error("kozmos-star.svg has no star to draw.");
  return svg(viewBox, [`<path d="${d}" fill="${colour}"/>`]);
}

/**
 * The glow of air on a planet's lit side: a thin ring just outside the
 * planet, in its rim colour, seen from -60 degrees through 48 percent of the
 * turn, brightest between 18 and 26.
 */
export function planetAirSvg(rim) {
  const stops = [
    [0, 0],
    [18, 1],
    [26, 1],
    [48, 0],
    [100, 0],
  ];
  return svg("0 0 100 100", [
    "<defs>",
    '<radialGradient id="air" gradientUnits="userSpaceOnUse" cx="50" cy="50" r="50">',
    ...stopsOf([
      [0.86, rim, 0],
      [0.92, rim],
      [1, rim, 0],
    ]),
    "</radialGradient>",
    '<mask id="lit" maskUnits="userSpaceOnUse" x="0" y="0" width="100" height="100">',
    ...wedges({
      cx: 50,
      cy: 50,
      r: 72,
      from: -60,
      fill: (percent) => grey(along(stops, percent)),
    }),
    "</mask>",
    "</defs>",
    '<rect width="100" height="100" fill="url(#air)" mask="url(#lit)"/>',
  ]);
}

/** Every file the script writes, by path, with its contents. */
export function cosmosSvgs({ orbits, darkCss, star }) {
  const token = (name) => tokenValue(darkCss, name);
  const files = new Map();
  orbits.forEach((orbit, index) => {
    const tone = TONES[orbit.tone];
    if (!tone)
      throw new Error(`Orbit ${index}'s tone "${orbit.tone}" has no colour.`);
    files.set(
      path.join(ART, `orbit-${index}.svg`),
      orbitSvg(orbit, token(tone)),
    );
  });
  files.set(path.join(ART, "galaxy.svg"), galaxySvg(token));
  files.set(path.join(ART, "ring.svg"), ringSvg(token));
  files.set(path.join(ART, "spark.svg"), sparkSvg(star, token));
  files.set(
    path.join(ART, "planet-air-violet.svg"),
    planetAirSvg(token("--primitives-colors-theme-variant-2-700")),
  );
  files.set(
    path.join(ART, "planet-air-blue.svg"),
    planetAirSvg(token("--primitives-colors-theme-variant-1-800")),
  );
  return files;
}

export function readInputs() {
  return {
    orbits: JSON.parse(fs.readFileSync(ORBITS, "utf8")),
    darkCss: fs.readFileSync(DARK_TOKENS, "utf8"),
    star: fs.readFileSync(STAR, "utf8"),
  };
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const files = cosmosSvgs(readInputs());
  const check = process.argv.includes("--check");
  const stale = [];
  // A file in the folder the script no longer draws is stale too.
  const left = fs.existsSync(ART)
    ? fs.readdirSync(ART).map((name) => path.join(ART, name))
    : [];
  for (const file of left.filter((file) => !files.has(file))) {
    if (check) stale.push(path.relative(SITE_ROOT, file));
    else {
      fs.rmSync(file);
      console.log(`removed ${path.relative(SITE_ROOT, file)}`);
    }
  }
  for (const [file, contents] of files) {
    const current = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : null;
    if (current === contents) continue;
    if (check) stale.push(path.relative(SITE_ROOT, file));
    else {
      fs.mkdirSync(path.dirname(file), { recursive: true });
      fs.writeFileSync(file, contents);
      console.log(`wrote ${path.relative(SITE_ROOT, file)}`);
    }
  }
  if (stale.length) {
    console.error(
      `generate-cosmos: these are out of date; run node scripts/generate-cosmos.mjs:\n  ${stale.join("\n  ")}`,
    );
    process.exit(1);
  }
  if (check) console.log("generate-cosmos: every cover image is current.");
}
